print("Welcome to the tip calculator")
bill = float(input("What is total bill?"))
people = int(input("How many people split the bill"))
tip = int(input("WHat percentage of tip would you like to give? 10. 12, or 15?"))
tip_percentage = float(tip / 100)
total_bill_with_tip = float(bill * (1 + tip_percentage))
bill_per_person = round(total_bill_with_tip / people,2)
print(f"each person should pay: {bill_per_person}")
print(type(bill_per_person))